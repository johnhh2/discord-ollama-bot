"""Print the SQL that creates the sidecar's SELECT-only account from the catalog.

Two modes:

    python -m botmcp.grants --template > scripts/mcp_db_user.sql
        The committed copy, with placeholders: reviewable in a diff, and
        tests/test_catalog.py checks it matches the catalog.

    python -m botmcp.grants | mysql -u root -p
        The real thing, with the account name, password and database read
        from the same env the sidecar runs with (MCP_DB_USER, MCP_DB_PASSWORD,
        DB_NAME; MCP_DB_ACCOUNT_HOST narrows the account's host, default '%').
        Inside the stack that is one command and no editing:
        docker compose --profile mcp run --rm mcp python -m botmcp.grants | mysql -u root -p
"""
from __future__ import annotations

import os
import sys

from botmcp import catalog

TEMPLATE_DB = "discord_bot"
TEMPLATE_USER = "botmcp"
TEMPLATE_PASSWORD = "CHANGE-ME-TO-A-LONG-RANDOM-PASSWORD"


def _quote(value: str) -> str:
    """A single-quoted MariaDB string literal."""
    return "'" + value.replace("\\", "\\\\").replace("'", "''") + "'"


def _ident(value: str) -> str:
    return "`" + value.replace("`", "``") + "`"


def render(db: str = TEMPLATE_DB, user: str = TEMPLATE_USER, password: str = TEMPLATE_PASSWORD, host: str = "%") -> str:
    account = f"{_quote(user)}@{_quote(host)}"
    lines = [
        "-- GENERATED by `python -m botmcp.grants` from botmcp/catalog.py. Do not edit by hand;",
        "-- edit the catalog and regenerate. tests/test_catalog.py checks the two agree.",
        "--",
        "-- Run as the MariaDB admin. The account, password and database come from the",
        "-- sidecar's own env (MCP_DB_USER, MCP_DB_PASSWORD, DB_NAME), so generate it",
        "-- from there rather than editing this file:",
        "--   docker compose --profile mcp run --rm mcp python -m botmcp.grants | mysql -u root -p",
        "-- MCP_DB_ACCOUNT_HOST narrows the account's host from '%' to a subnet.",
        "--",
        "-- Column-level SELECT only. No INSERT/UPDATE/DELETE/DDL, no other schema,",
        "-- no FILE/PROCESS/SUPER. The session is also forced read-only and",
        "-- time-limited by the sidecar itself (botmcp/db.py).",
        "",
        f"CREATE USER IF NOT EXISTS {account} IDENTIFIED BY {_quote(password)};",
        f"ALTER USER {account} IDENTIFIED BY {_quote(password)} WITH MAX_USER_CONNECTIONS 8 MAX_STATEMENT_TIME 5;",
        f"REVOKE ALL PRIVILEGES, GRANT OPTION FROM {account};",
        "",
    ]
    for name, table in sorted(catalog.readable().items()):
        cols = ", ".join(table.columns)
        if table.hidden:
            lines.append("-- hidden: " + "; ".join(f"{c} ({why})" for c, why in table.hidden.items()))
        lines.append(f"GRANT SELECT ({cols}) ON {_ident(db)}.{_ident(name)} TO {account};")
    lines.append("")
    lines.append("-- No grant at all on:")
    for name, table in sorted(catalog.TABLES.items()):
        if not table.readable:
            lines.append(f"--   {name}: {table.never}")
    lines.append("")
    lines.append("FLUSH PRIVILEGES;")
    return "\n".join(lines) + "\n"


def render_from_env(env=os.environ) -> str:
    missing = [k for k in ("MCP_DB_USER", "MCP_DB_PASSWORD", "DB_NAME") if not env.get(k)]
    if missing:
        raise SystemExit(f"botmcp.grants: set {', '.join(missing)} (or pass --template for the placeholder copy)")
    return render(db=env["DB_NAME"], user=env["MCP_DB_USER"], password=env["MCP_DB_PASSWORD"],
                  host=env.get("MCP_DB_ACCOUNT_HOST") or "%")


def main(argv: list) -> int:
    sys.stdout.write(render() if "--template" in argv else render_from_env())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
